"""LAYER 1 — the reusable data foundation.

This file does ONE thing: given a source id, read that source's rows from a CSV.
It is deliberately domain-agnostic — there are no conference words here (no
"sessions", "tracks", "rooms", "speakers"). That is the point: this layer could
back any application. WHAT the sources are and HOW they relate lives in the
governed semantic layer (semantic/*.md), not in this code.

A "source" is just an id mapped to a CSV path. The mapping comes from
semantic.list_sources(), which mirrors semantic/sources.md. Add a source by
editing the markdown + the mirror dict — you do not edit this file.
"""
from __future__ import annotations
import csv
from pathlib import Path

import semantic  # the governed layer owns the source list (mirrors sources.md)

# A row is just a dict of column -> string value, exactly like csv.DictReader
# hands back. We keep it that simple on purpose.
Row = dict[str, str]

# All data lives under this folder. Reads are confined to it (see read_source).
_DATA_ROOT = Path(__file__).resolve().parent


def list_sources() -> dict[str, str]:
    """Return the known sources as {source_id: relative_csv_path}.

    Delegates to the semantic layer so there is a single source of truth. The
    agent discovers what exists from here at runtime — it is not hardcoded in
    any prompt."""
    return semantic.list_sources()


def read_source(source_id: str) -> list[Row] | dict:
    """Read all rows for one source id, or return a plain error dict.

    Security: the id is validated against the known sources before any file is
    touched, and the resolved path must stay inside the data root — so a crafted
    id can never read an arbitrary file. Errors are returned as data, never
    raised, so a bad id cannot crash the agent.

    To add a non-CSV source you'd add a reader here (e.g. a SQLite or HTTP
    branch); today every source is a CSV, so one reader is all we need.
    """
    sources = list_sources()
    if source_id not in sources:
        return {"error": f"unknown source_id '{source_id}'", "source_id": source_id}

    path = (_DATA_ROOT / sources[source_id]).resolve()
    if _DATA_ROOT != path and _DATA_ROOT not in path.parents:   # path confinement
        return {"error": f"source location escapes data root: {source_id}",
                "source_id": source_id}
    try:
        with path.open(newline="", encoding="utf-8") as f:
            return list(csv.DictReader(f))
    except Exception as e:
        return {"error": f"read failed for '{source_id}': {e}", "source_id": source_id}
